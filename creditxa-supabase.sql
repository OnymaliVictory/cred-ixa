-- Returns true if the currently authenticated user is a linked,
-- active admin. SECURITY DEFINER so it can read admin_users
-- without needing a separate RLS policy exposed to everyone
-- (avoids recursive-policy problems too).
CREATE OR REPLACE FUNCTION is_admin()
RETURNS BOOLEAN
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
  SELECT EXISTS (
    SELECT 1 FROM admin_users au
    WHERE au.auth_user_id = auth.uid() AND au.active = true
  );
$$;

-- Called once, right after an admin signs in with Supabase Auth
-- (email + password). Links the auth account to the admin_users
-- row on first login (matched by email), refuses if the email
-- isn't a known/active admin, updates last_login, and writes an
-- 'admin_login' activity entry. This replaces the old hard-coded
-- ADMIN_EMAIL / ADMIN_PASS check that used to live in admin.html.
CREATE OR REPLACE FUNCTION admin_login_check()
RETURNS TABLE(ok BOOLEAN, admin_name TEXT, admin_role TEXT)
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
  v_email TEXT := auth.jwt() ->> 'email';
  v_row   admin_users;
BEGIN
  IF auth.uid() IS NULL OR v_email IS NULL THEN
    RETURN QUERY SELECT false, NULL::TEXT, NULL::TEXT; RETURN;
  END IF;

  SELECT * INTO v_row FROM admin_users WHERE lower(email) = lower(v_email) AND active = true LIMIT 1;
  IF v_row.id IS NULL THEN
    RETURN QUERY SELECT false, NULL::TEXT, NULL::TEXT; RETURN;
  END IF;

  IF v_row.auth_user_id IS NULL THEN
    UPDATE admin_users SET auth_user_id = auth.uid(), last_login = now() WHERE id = v_row.id;
  ELSIF v_row.auth_user_id <> auth.uid() THEN
    -- email is registered to a different auth account — refuse
    RETURN QUERY SELECT false, NULL::TEXT, NULL::TEXT; RETURN;
  ELSE
    UPDATE admin_users SET last_login = now() WHERE id = v_row.id;
  END IF;

  INSERT INTO activity_log(actor_type, actor_email, action, details)
  VALUES ('admin', v_email, 'admin_login', NULL);

  RETURN QUERY SELECT true, v_row.name, v_row.role;
END;
$$;
GRANT EXECUTE ON FUNCTION admin_login_check() TO authenticated;

-- Lets any signed-in user (admin or client) log an activity event
-- about themselves — used by login.html / admin.html to record
-- 'login' and 'logout' (signup + email-verified are logged
-- automatically by the auth.users triggers below).
CREATE OR REPLACE FUNCTION log_activity(
  p_action      TEXT,
  p_details     TEXT DEFAULT NULL,
  p_entity_type TEXT DEFAULT NULL,
  p_entity_id   UUID DEFAULT NULL
) RETURNS VOID
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
  v_email TEXT := auth.jwt() ->> 'email';
  v_type  TEXT;
BEGIN
  IF auth.uid() IS NULL OR v_email IS NULL THEN
    RAISE EXCEPTION 'Not authenticated';
  END IF;
  v_type := CASE WHEN is_admin() THEN 'admin' ELSE 'client' END;
  INSERT INTO activity_log (actor_type, actor_email, action, entity_type, entity_id, details)
  VALUES (v_type, v_email, p_action, p_entity_type, p_entity_id, p_details);
END;
$$;
GRANT EXECUTE ON FUNCTION log_activity(TEXT,TEXT,TEXT,UUID) TO authenticated;

-- Public loan-application submission. This is the ONLY way the
-- public website is allowed to write clients / loan_applications
-- rows (see RLS below) — it validates input, finds-or-creates the
-- client, creates the application, and logs it, all atomically and
-- without ever exposing the clients table to direct anon access.
CREATE OR REPLACE FUNCTION submit_loan_application(
  p_full_name          TEXT,
  p_email              TEXT,
  p_nif                TEXT,
  p_phone              TEXT,
  p_address             TEXT,
  p_date_of_birth       DATE,
  p_nationality         TEXT,
  p_residence_status    TEXT,
  p_id_document_type    TEXT,
  p_id_document_number  TEXT,
  p_monthly_income      NUMERIC,
  p_iban                TEXT,
  p_employment_status   TEXT,
  p_loan_type           TEXT,
  p_amount              NUMERIC,
  p_term_months         INTEGER,
  p_annual_rate         NUMERIC,
  p_loan_purpose        TEXT,
  p_existing_debts      NUMERIC
) RETURNS TEXT
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
  v_client_id UUID;
  v_app_no    TEXT;
  v_code      TEXT;
BEGIN
  IF p_full_name IS NULL OR length(trim(p_full_name)) < 2 THEN
    RAISE EXCEPTION 'Nome inválido';
  END IF;
  IF p_email IS NULL OR p_email !~* '^[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}$' THEN
    RAISE EXCEPTION 'Email inválido';
  END IF;
  IF p_nif IS NULL OR p_nif !~ '^[0-9]{9}$' THEN
    RAISE EXCEPTION 'NIF inválido';
  END IF;
  IF p_loan_type NOT IN ('personal','mortgage','car','consolidation') THEN
    RAISE EXCEPTION 'Tipo de crédito inválido';
  END IF;
  IF p_amount IS NULL OR p_amount <= 0 THEN
    RAISE EXCEPTION 'Montante inválido';
  END IF;
  IF p_term_months IS NULL OR p_term_months <= 0 THEN
    RAISE EXCEPTION 'Prazo inválido';
  END IF;

  SELECT id INTO v_client_id FROM clients
  WHERE nif = p_nif OR email = p_email
  ORDER BY (nif = p_nif) DESC LIMIT 1;

  IF v_client_id IS NULL THEN
    v_code := 'C-' || to_char(now(),'YY') || lpad(nextval('client_code_seq')::text, 6, '0');
    INSERT INTO clients (
      client_code, full_name, email, nif, phone, address, date_of_birth,
      monthly_income, nationality, residence_status, id_document_type,
      id_document_number, iban, employment_status, status
    ) VALUES (
      v_code, p_full_name, p_email, p_nif, p_phone, p_address, p_date_of_birth,
      p_monthly_income, p_nationality, p_residence_status, p_id_document_type,
      p_id_document_number, p_iban, p_employment_status, 'active'
    ) RETURNING id INTO v_client_id;
  ELSE
    UPDATE clients SET
      full_name          = p_full_name,
      phone              = COALESCE(p_phone, phone),
      address            = COALESCE(p_address, address),
      date_of_birth      = COALESCE(p_date_of_birth, date_of_birth),
      monthly_income     = COALESCE(p_monthly_income, monthly_income),
      nationality        = COALESCE(p_nationality, nationality),
      residence_status   = COALESCE(p_residence_status, residence_status),
      id_document_type   = COALESCE(p_id_document_type, id_document_type),
      id_document_number = COALESCE(p_id_document_number, id_document_number),
      iban               = COALESCE(p_iban, iban),
      employment_status  = COALESCE(p_employment_status, employment_status)
    WHERE id = v_client_id;
  END IF;

  v_app_no := 'CR-' || to_char(now(),'YYYY') || '-' || lpad(nextval('application_no_seq')::text, 5, '0');

  INSERT INTO loan_applications (
    application_no, client_id, loan_type, amount, term_months, annual_rate,
    loan_purpose, existing_debts, source, status
  ) VALUES (
    v_app_no, v_client_id, p_loan_type, p_amount, p_term_months, p_annual_rate,
    p_loan_purpose, COALESCE(p_existing_debts, 0), 'website', 'pending'
  );

  INSERT INTO activity_log (actor_type, actor_email, action, entity_type, details)
  VALUES ('system', p_email, 'application_submitted', 'application', v_app_no);

  RETURN v_app_no;
END;
$$;
GRANT EXECUTE ON FUNCTION submit_loan_application(
  TEXT,TEXT,TEXT,TEXT,TEXT,DATE,TEXT,TEXT,TEXT,TEXT,NUMERIC,TEXT,TEXT,TEXT,NUMERIC,INTEGER,NUMERIC,TEXT,NUMERIC
) TO anon, authenticated;

-- Lets an admin add a client manually from the admin panel (the
-- "Novo Cliente" modal) with the same server-generated client_code
-- scheme used by submit_loan_application, instead of the panel
-- inserting rows directly (which used to silently do nothing).
CREATE OR REPLACE FUNCTION admin_create_client(
  p_full_name      TEXT,
  p_email          TEXT,
  p_nif            TEXT,
  p_phone          TEXT,
  p_address        TEXT,
  p_date_of_birth  DATE,
  p_monthly_income NUMERIC
) RETURNS UUID
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
  v_client_id UUID;
  v_code      TEXT;
BEGIN
  IF NOT is_admin() THEN
    RAISE EXCEPTION 'Apenas administradores podem criar clientes manualmente';
  END IF;
  IF p_full_name IS NULL OR length(trim(p_full_name)) < 2 THEN RAISE EXCEPTION 'Nome inválido'; END IF;
  IF p_email IS NULL OR p_email !~* '^[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}$' THEN RAISE EXCEPTION 'Email inválido'; END IF;
  IF p_nif IS NULL OR p_nif !~ '^[0-9]{9}$' THEN RAISE EXCEPTION 'NIF inválido'; END IF;

  v_code := 'C-' || to_char(now(),'YY') || lpad(nextval('client_code_seq')::text, 6, '0');
  INSERT INTO clients (client_code, full_name, email, nif, phone, address, date_of_birth, monthly_income, status)
  VALUES (v_code, p_full_name, p_email, p_nif, p_phone, p_address, p_date_of_birth, p_monthly_income, 'active')
  RETURNING id INTO v_client_id;

  INSERT INTO activity_log (actor_type, actor_email, action, entity_type, entity_id, details)
  VALUES ('admin', auth.jwt() ->> 'email', 'created_client', 'client', v_client_id, p_full_name);

  RETURN v_client_id;
END;
$$;
GRANT EXECUTE ON FUNCTION admin_create_client(TEXT,TEXT,TEXT,TEXT,TEXT,DATE,NUMERIC) TO authenticated;

-- Auto-log account creation the moment Supabase Auth creates the
-- user (fires before the person ever calls the app again), and
-- auto-log the moment their email gets confirmed.
CREATE OR REPLACE FUNCTION handle_new_auth_user()
RETURNS TRIGGER LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
  INSERT INTO activity_log (actor_type, actor_email, action, details)
  VALUES ('client', NEW.email, 'signup', 'Conta criada');
  RETURN NEW;
END;
$$;
CREATE TRIGGER on_auth_user_created
  AFTER INSERT ON auth.users
  FOR EACH ROW EXECUTE FUNCTION handle_new_auth_user();

CREATE OR REPLACE FUNCTION handle_auth_user_verified()
RETURNS TRIGGER LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
  IF OLD.email_confirmed_at IS NULL AND NEW.email_confirmed_at IS NOT NULL THEN
    INSERT INTO activity_log (actor_type, actor_email, action, details)
    VALUES ('client', NEW.email, 'email_verified', 'Email confirmado');
  END IF;
  RETURN NEW;
END;
$$;
CREATE TRIGGER on_auth_user_verified
  AFTER UPDATE ON auth.users
  FOR EACH ROW EXECUTE FUNCTION handle_auth_user_verified();

