-- ── 1. CLIENTS ──────────────────────────────────────────────────
CREATE TABLE clients (
  id                 UUID         PRIMARY KEY DEFAULT gen_random_uuid(),
  client_code        TEXT         UNIQUE NOT NULL,
  full_name          TEXT         NOT NULL,
  email              TEXT         UNIQUE NOT NULL,
  nif                TEXT         UNIQUE NOT NULL,
  phone              TEXT,
  address            TEXT,
  date_of_birth      DATE,
  monthly_income     NUMERIC(12,2),
  nationality        TEXT,
  residence_status   TEXT         CHECK (residence_status IN ('citizen','eu_resident','non_eu_resident','non_resident')),
  id_document_type   TEXT         CHECK (id_document_type IN ('cc','passport','residence_permit')),
  id_document_number TEXT,
  iban               TEXT,
  employment_status  TEXT         CHECK (employment_status IN ('employed','self_employed','business_owner','unemployed','retired','student')),
  kyc_verified       BOOLEAN      NOT NULL DEFAULT false,
  kyc_verified_at    TIMESTAMPTZ,
  status             TEXT         NOT NULL DEFAULT 'active' CHECK (status IN ('active','inactive','blocked','overdue')),
  auth_user_id       UUID         UNIQUE REFERENCES auth.users(id) ON DELETE SET NULL,
  created_at         TIMESTAMPTZ  NOT NULL DEFAULT now(),
  updated_at         TIMESTAMPTZ  NOT NULL DEFAULT now(),
  CONSTRAINT chk_client_email CHECK (email ~* '^[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}$'),
  CONSTRAINT chk_client_nif   CHECK (nif ~ '^[0-9]{9}$')
);

-- ── 2. LOAN APPLICATIONS ────────────────────────────────────────
CREATE TABLE loan_applications (
  id              UUID         PRIMARY KEY DEFAULT gen_random_uuid(),
  application_no  TEXT         UNIQUE NOT NULL,
  client_id       UUID         NOT NULL REFERENCES clients(id) ON DELETE CASCADE,
  loan_type       TEXT         NOT NULL CHECK (loan_type IN ('personal','mortgage','car','consolidation')),
  amount          NUMERIC(12,2) NOT NULL CHECK (amount > 0),
  term_months     INTEGER      NOT NULL CHECK (term_months > 0),
  annual_rate     NUMERIC(6,4) NOT NULL CHECK (annual_rate >= 0),
  monthly_payment NUMERIC(12,2),
  loan_purpose    TEXT,
  existing_debts  NUMERIC(12,2) DEFAULT 0,
  source          TEXT         DEFAULT 'website',
  status          TEXT         NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','review','approved','rejected')),
  notes           TEXT,
  reviewed_by     TEXT,
  reviewed_at     TIMESTAMPTZ,
  created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
  updated_at      TIMESTAMPTZ  NOT NULL DEFAULT now()
);

-- ── 3. LOANS (active contracts) ─────────────────────────────────
CREATE TABLE loans (
  id               UUID         PRIMARY KEY DEFAULT gen_random_uuid(),
  contract_no      TEXT         UNIQUE NOT NULL,
  application_id   UUID         UNIQUE REFERENCES loan_applications(id),
  client_id        UUID         NOT NULL REFERENCES clients(id) ON DELETE CASCADE,
  loan_type        TEXT         NOT NULL CHECK (loan_type IN ('personal','mortgage','car','consolidation')),
  principal        NUMERIC(12,2) NOT NULL CHECK (principal > 0),
  annual_rate      NUMERIC(6,4) NOT NULL CHECK (annual_rate >= 0),
  term_months      INTEGER      NOT NULL CHECK (term_months > 0),
  monthly_payment  NUMERIC(12,2) NOT NULL,
  start_date       DATE         NOT NULL,
  end_date         DATE         NOT NULL,
  amount_paid      NUMERIC(12,2) NOT NULL DEFAULT 0,
  amount_remaining NUMERIC(12,2) NOT NULL,
  status           TEXT         NOT NULL DEFAULT 'active' CHECK (status IN ('active','paid_off','defaulted','early_settled')),
  created_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
  updated_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
  CONSTRAINT chk_loan_dates CHECK (end_date > start_date)
);

