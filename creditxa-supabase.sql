-- ================================================================
--  CREDITXA — Complete Database Schema (v2 — fixed & consolidated)
--  Single file. Paste ENTIRELY into Supabase SQL Editor → Run.
--
--  This script always starts by dropping every Creditxa object it
--  knows about, so you can paste this same file again in the
--  future to wipe and rebuild a perfectly clean database.
--  It does NOT touch auth.users — Supabase manages that separately.
--
--  WHAT THIS VERSION FIXES vs the original schema:
--   1. Real Row-Level-Security: the anon key could previously
--      INSERT/UPDATE/SELECT every row of every table (including
--      other people's KYC data). Public writes now only happen
--      through SECURITY DEFINER functions (RPCs) that validate
--      input server-side; direct table access is limited to the
--      record owner (a logged-in client) or a verified admin.
--   2. admin_users now links to a real Supabase Auth account
--      (auth_user_id) instead of a password hard-coded in HTML.
--   3. activity_log now records BOTH admin actions and client
--      account activity (signup / email verified / login /
--      logout), tagged with actor_type, so the admin panel can
--      show a real activity feed.
--   4. Application numbers / client codes are generated by the
--      database (sequences) instead of Date.now() in the browser,
--      removing a duplicate-key race condition.
-- ================================================================

