CREATE OR REPLACE VIEW vw_dashboard_summary AS
SELECT
  (SELECT COUNT(*) FROM clients WHERE status = 'active')                                   AS active_clients,
  (SELECT COUNT(*) FROM loan_applications WHERE status = 'pending')                        AS pending_applications,
  (SELECT COUNT(*) FROM loan_applications WHERE status = 'review')                         AS review_applications,
  (SELECT COUNT(*) FROM loans WHERE status = 'active')                                     AS active_loans,
  (SELECT COUNT(*) FROM loans WHERE status = 'defaulted')                                  AS defaulted_loans,
  (SELECT COALESCE(SUM(principal),0) FROM loans WHERE status='active')                     AS total_portfolio,
  (SELECT COALESCE(SUM(amount),0) FROM payments WHERE status='paid'
     AND DATE_TRUNC('month',payment_date)=DATE_TRUNC('month',CURRENT_DATE))                AS received_this_month,
  (SELECT COUNT(*) FROM messages WHERE status='unread')                                    AS unread_messages,
  (SELECT COUNT(*) FROM newsletter_subscribers WHERE subscribed=true)                      AS newsletter_count,
  (SELECT COUNT(*) FROM activity_log WHERE actor_type='client' AND action='signup'
     AND created_at >= CURRENT_DATE)                                                       AS signups_today;

CREATE OR REPLACE VIEW vw_applications_full AS
SELECT
  la.id, la.application_no, la.loan_type, la.amount, la.term_months,
  ROUND(la.annual_rate*100,4) AS tan_percent,
  la.status, la.notes, la.loan_purpose, la.existing_debts, la.source,
  la.created_at, la.reviewed_at, la.reviewed_by,
  c.id AS client_id, c.full_name AS client_name, c.email AS client_email,
  c.nif AS client_nif, c.phone AS client_phone,
  c.monthly_income, c.nationality, c.residence_status,
  c.id_document_type, c.id_document_number, c.iban,
  c.employment_status, c.date_of_birth, c.address, c.kyc_verified
FROM loan_applications la
JOIN clients c ON la.client_id = c.id
ORDER BY la.created_at DESC;

CREATE OR REPLACE VIEW vw_payments_full AS
SELECT
  p.id, p.payment_ref, p.amount, p.payment_method,
  p.payment_date, p.status, p.notes, p.created_at,
  l.contract_no, l.loan_type,
  c.full_name AS client_name, c.email AS client_email, c.phone AS client_phone
FROM payments p
JOIN loans   l ON p.loan_id=l.id
JOIN clients c ON p.client_id=c.id
ORDER BY p.payment_date DESC, p.created_at DESC;

CREATE OR REPLACE VIEW vw_clients_overview AS
SELECT
  c.id, c.client_code, c.full_name, c.email, c.nif, c.phone,
  c.status, c.kyc_verified, c.employment_status, c.monthly_income, c.created_at,
  COUNT(DISTINCT la.id)                                            AS total_applications,
  COUNT(DISTINCT l.id) FILTER (WHERE l.status='active')           AS active_loans,
  COALESCE(SUM(l.principal) FILTER (WHERE l.status='active'),0)   AS total_borrowed
FROM clients c
LEFT JOIN loan_applications la ON la.client_id=c.id
LEFT JOIN loans l ON l.client_id=c.id
GROUP BY c.id ORDER BY c.created_at DESC;

-- Unified feed used by Admin → Atividade: admin actions AND
-- client account activity (signup / email verified / login / logout).
CREATE OR REPLACE VIEW vw_activity_feed AS
SELECT id, actor_type, actor_email, action, entity_type, entity_id, details, created_at
FROM activity_log
ORDER BY created_at DESC;

