-- clients — no direct public INSERT anymore (goes through
-- submit_loan_application). A signed-in client can see / update
-- their own record (matched by auth_user_id, or by email on their
-- very first login before the link is made); an admin can see/edit
-- everyone.
CREATE POLICY "clients_select" ON clients FOR SELECT
  USING (is_admin() OR auth.uid() = auth_user_id OR email = (auth.jwt() ->> 'email'));
CREATE POLICY "clients_update" ON clients FOR UPDATE
  USING (is_admin() OR auth.uid() = auth_user_id OR (auth_user_id IS NULL AND email = (auth.jwt() ->> 'email')))
  WITH CHECK (is_admin() OR auth.uid() = auth_user_id);
CREATE POLICY "clients_insert_admin" ON clients FOR INSERT
  WITH CHECK (is_admin());

-- loan_applications — same idea: public submission via RPC only;
-- the owning client can read their own applications; only admins
-- can change status.
CREATE POLICY "apps_select" ON loan_applications FOR SELECT
  USING (
    is_admin() OR EXISTS (
      SELECT 1 FROM clients c WHERE c.id = loan_applications.client_id
        AND (c.auth_user_id = auth.uid() OR c.email = (auth.jwt() ->> 'email'))
    )
  );
CREATE POLICY "apps_update_admin" ON loan_applications FOR UPDATE USING (is_admin());
CREATE POLICY "apps_insert_admin" ON loan_applications FOR INSERT WITH CHECK (is_admin());

-- loans — owning client can view; only admin can write.
CREATE POLICY "loans_select" ON loans FOR SELECT
  USING (
    is_admin() OR EXISTS (
      SELECT 1 FROM clients c WHERE c.id = loans.client_id
        AND (c.auth_user_id = auth.uid() OR c.email = (auth.jwt() ->> 'email'))
    )
  );
CREATE POLICY "loans_insert_admin" ON loans FOR INSERT WITH CHECK (is_admin());
CREATE POLICY "loans_update_admin" ON loans FOR UPDATE USING (is_admin());

-- payments — owning client can view; only admin can write.
CREATE POLICY "payments_select" ON payments FOR SELECT
  USING (
    is_admin() OR EXISTS (
      SELECT 1 FROM clients c WHERE c.id = payments.client_id
        AND (c.auth_user_id = auth.uid() OR c.email = (auth.jwt() ->> 'email'))
    )
  );
